#!/usr/bin/env python3
"""Generate the typed mihomo listener inventory from the pinned upstream source."""
from pathlib import Path
import hashlib,json,re,sys,tarfile,urllib.request
ROOT=Path(__file__).resolve().parents[1]
VERSION='1.19.33'
UPSTREAM=ROOT/'runtime/upstream'
ARCHIVE=UPSTREAM/f'mihomo-v{VERSION}.tar.gz'
UPSTREAM.mkdir(parents=True,exist_ok=True)
if not ARCHIVE.exists():
    urllib.request.urlretrieve(f'https://codeload.github.com/MetaCubeX/mihomo/tar.gz/refs/tags/v{VERSION}',ARCHIVE)
EXPECTED_SHA='e7c596b37ff27ec487d19b1920f73e0c97a78067ea35766530ee9659ade72711'
assert hashlib.sha256(ARCHIVE.read_bytes()).hexdigest()==EXPECTED_SHA,'Pinned upstream archive checksum mismatch.'
SOURCE=UPSTREAM/f'mihomo-{VERSION}/listener/inbound'
if not SOURCE.exists():
    with tarfile.open(ARCHIVE) as archive:archive.extractall(UPSTREAM,filter='data')
structs={}
for file in SOURCE.glob('*.go'):
    for name,body in re.findall(r'^type (\w+) struct \{(.*?)^\}',file.read_text(),re.M|re.S):
        fields=[]
        for line in body.splitlines():
            match=re.match(r'\s*(\w+)\s+(\S+)\s+`inbound:"([^"]+)"`',line)
            if match and match[3].split(',')[0]!='-':
                fields.append((match[3].split(',')[0],match[2],',omitempty' not in match[3]))
        structs[name]=fields
protocols={'vless':'VlessOption','vmess':'VmessOption','trojan':'TrojanOption','shadowsocks':'ShadowSocksOption','snell':'SnellOption','mieru':'MieruOption','sudoku':'SudokuOption','trusttunnel':'TrustTunnelOption','tuic':'TuicOption','hysteria2':'Hysteria2Option','hysteria2-realm':'Hysteria2RealmServerOption','shadowquic':'ShadowQuicOption','anytls':'AnyTLSOption','http':'HTTPOption','socks':'SocksOption','mixed':'MixedOption','redirect':'RedirOption','tproxy':'TProxyOption','tun':'TunOption','tunnel':'TunnelOption'}
def fields(name,prefix=()):
    result=[]
    for key,kind,required in structs[name]:
        path=prefix+(key,)
        plain=kind.lstrip('*')
        if plain in structs:
            result+=fields(plain,path)
        elif kind.startswith('[]') and kind[2:] in structs:
            result.append({'path':list(path),'type':'rows','required':required,'children':fields(kind[2:])})
        elif kind.startswith('map[string]'):
            target=kind[len('map[string]'):]
            children=[{'path':['key'],'type':'string','required':True}]
            if target in structs:children+=fields(target)
            else:children.append({'path':['value'],'type':target,'required':True})
            result.append({'path':list(path),'type':'map','required':required,'children':children})
        elif kind=='AuthUsers':
            result.append({'path':list(path),'type':'users','required':required})
        else:
            assert plain in ['string','bool','int','uint64','uint32','uint16','int64','[]string','[]int','[]uint32','[]uint16','[]netip.Prefix','[]netip.Addr','C.TUNStack'],(name,key,kind)
            result.append({'path':list(path),'type':plain,'required':required,'nullable':kind.startswith('*')})
    return result
# Keep the panel focused on native protocol operation and conventional transports.
# Advanced upstream experiments are deliberately outside the product surface.
supported={
 'vless':{'ws-path','grpc-service-name','xhttp-config.path','xhttp-config.host','xhttp-config.mode'},
 'vmess':{'ws-path','grpc-service-name'},'trojan':{'ws-path','grpc-service-name'},
 'shadowsocks':{'cipher','udp'},'snell':{'version','udp'},'mieru':{'traffic-pattern'},
 'sudoku':{'aead-method','padding-min','padding-max','handshake-timeout','disable-http-mask','http-mask-mode','path-root'},
 'trusttunnel':{'congestion-controller'},
 'tuic':{'congestion-controller','max-idle-time','authentication-timeout','alpn','max-udp-relay-packet-size'},
 'hysteria2':{'obfs','obfs-password','max-idle-time','alpn','up','down','ignore-client-bandwidth','masquerade'},
 'hysteria2-realm':{'alpn'},
 'shadowquic':{'jls-upstream.addr','jls-upstream.sni','alpn','zero-rtt','congestion-controller','up','down','max-idle-time'},
 'anytls':{'padding-scheme'},'http':set(),'socks':{'udp'},'mixed':{'udp'},'redirect':set(),'tproxy':{'udp'},
 'tun':{'device','stack','dns-mode','dns-hijack','auto-route','auto-detect-interface','mtu','inet4-address','inet6-address','strict-route','route-address','route-exclude-address','udp-timeout'},
 'tunnel':{'target'},
}
inventory={protocol:[field for field in fields(name) if '.'.join(field['path']) in supported[protocol]] for protocol,name in protocols.items()}
output=ROOT/'app/api/lib/src/cores/mihomo_native.g.dart'
output.write_text('// Generated by tool/generate_mihomo_schema.py from MetaCubeX/mihomo v'+VERSION+'.\n// Curated native options; UI policy and defaults are defined separately.\nconst mihomoNativeInventory=<String,List<Map<String,dynamic>>>'+json.dumps(inventory,indent=2)+';\n')
print(f'Generated {len(inventory)} pinned listener definitions.')
